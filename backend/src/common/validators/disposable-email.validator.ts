/**
 * Check if an email domain is a known disposable/temporary email service
 * @param email - The email address to check
 * @returns true if the email uses a disposable domain
 */
export function isDisposableEmail(email: string): boolean {
    if (!email || !email.includes("@")) return false
    const domain = email.split("@")[1].toLowerCase().trim()
    return DISPOSABLE_DOMAINS.has(domain)
}

/**
 * Get the blocked domain from an email, if it's disposable
 * @param email - The email address to check
 * @returns The domain if blocked, null if allowed
 */
export function getBlockedDomain(email: string): string | null {
    if (!email || !email.includes("@")) return null
    const domain = email.split("@")[1].toLowerCase().trim()
    return DISPOSABLE_DOMAINS.has(domain) ? domain : null
}
